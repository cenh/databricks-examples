# MAGIC %md
# MAGIC ## Overview
# MAGIC
# MAGIC Attribute-Based Access Control (ABAC) in Databricks Unity Catalog went generally
# MAGIC available on April 28, 2026. Instead of writing an access control list per table, ABAC
# MAGIC lets you define a policy once, for example "hide EU customer rows", and have it apply
# MAGIC automatically to every object that carries the matching tag.
# MAGIC
# MAGIC ABAC complements, rather than replaces, Unity Catalog's privilege model. You still grant
# MAGIC privileges like `SELECT`; ABAC layers conditional, tag-driven access on top of that.
# MAGIC Row filter and column mask policies apply to tables, materialized views, and streaming
# MAGIC tables. There is also a separate GRANT policy type (Beta) for dynamic `EXECUTE` grants on
# MAGIC models, which this notebook does not cover.
# MAGIC
# MAGIC ABAC relies on three components:
# MAGIC
# MAGIC 1. **Governed tags** - account-level tag keys, for example `pii:ssn` or `geo_region:region`.
# MAGIC 2. **Policies** - a row filter (hides rows) or a column mask (masks column values),
# MAGIC    applied at the catalog, schema, or table level. A policy on a catalog or schema
# MAGIC    cascades down to every table underneath it. Tag inheritance has one exception: tags
# MAGIC    inherited from a catalog or schema apply during policy evaluation everywhere except at
# MAGIC    the column level.
# MAGIC 3. **User-defined functions (UDFs)** - the policy calls a UDF to decide whether to hide a
# MAGIC    row or what value to substitute for a masked column.
# MAGIC
# MAGIC At GA, policies can be created three ways: the Catalog Explorer UI, the `CREATE POLICY`
# MAGIC SQL statement (Databricks Runtime 16.4+ or serverless), or the REST API, SDK, or
# MAGIC Terraform. This notebook shows both the UI path (as reference, since it cannot be
# MAGIC scripted) and the SQL path (fully runnable) for each policy.
# MAGIC
# MAGIC Use ABAC when you manage large catalogs, need dynamic per-region or per-persona rules, or
# MAGIC must enforce compliance rules such as GDPR, PCI, or HIPAA at scale. Avoid it, for now,
# MAGIC when:
# MAGIC
# MAGIC - You need to attach a policy directly to a **view**. Policies still cannot be attached to
# MAGIC   a view, but policies on the underlying tables are enforced when you query through the
# MAGIC   view, evaluated using the session user's identity.
# MAGIC - You expect multiple row filters or column masks to combine automatically on the same
# MAGIC   object. Only one distinct row filter can resolve per user per table, and only one
# MAGIC   distinct column mask can resolve per user per column, so combine logic with `AND` inside
# MAGIC   a single UDF instead of stacking policies.
# MAGIC - Your compute is older than **DBR 16.4** and isn't serverless. Standard or dedicated
# MAGIC   compute on older runtimes can't read ABAC-secured tables.
# MAGIC
# MAGIC This notebook:
# MAGIC
# MAGIC 1. Creates a small CH Enterprise `clients` table with US and EU records (**Setup**).
# MAGIC 2. Walks through creating the governed tags that this tutorial depends on
# MAGIC    (**Manual setup required**).
# MAGIC 3. Tags the sensitive columns.
# MAGIC 4. Creates a UDF and a row filter policy that hides EU customer rows.
# MAGIC 5. Creates a UDF and a column mask policy that redacts SSNs.
# MAGIC 6. Verifies the enforced behavior.
# MAGIC 7. Removes the policies, functions, and sample table (**Cleanup**).

