# MAGIC %md
# MAGIC ## Manual setup required
# MAGIC
# MAGIC Governed tags are account-level objects: the tag key itself, its allowed values, and who
# MAGIC is permitted to apply it are defined once per account, not per workspace, and there is no
# MAGIC SQL or PySpark statement that creates one. Complete this before running the tagging cell
# MAGIC below if you want it enforced as a governed tag rather than an ordinary one; the
# MAGIC `ALTER ... SET TAGS` statements later in this notebook will still run without it, they
# MAGIC just apply as plain, ungoverned tags until the policy exists.
# MAGIC
# MAGIC ### 1. Create the governed tags
# MAGIC
# MAGIC This tutorial uses two tag keys: `pii` (values `ssn` and `address`) and `geo_region`
# MAGIC (value `region`). For each one:
# MAGIC
# MAGIC 1. In the workspace sidebar, open **Data**, then **Governance**, then **Governed Tags**
# MAGIC    (account admins can also reach this from the account console under **Governance**).
# MAGIC 2. Click **Create governed tag**.
# MAGIC 3. Enter the tag key exactly as used in this notebook, `pii` or `geo_region`. Tag keys are
# MAGIC    case sensitive.
# MAGIC 4. Add the allowed values for that key: `ssn` and `address` for `pii`; `region` for
# MAGIC    `geo_region`. You can also leave a key unrestricted if you don't want to enforce a
# MAGIC    fixed value list.
# MAGIC 5. Set who is permitted to create, manage, and assign the tag, either account-wide or per
# MAGIC    tag, from the same screen.
# MAGIC 6. Click **Create**, and repeat for the second tag key.
# MAGIC
# MAGIC Allow up to roughly 30 seconds (occasionally longer) for the tag and its permissions to
# MAGIC propagate before you rely on it elsewhere.
# MAGIC
# MAGIC ### 2. Everything after this is scriptable
# MAGIC
# MAGIC Once the `pii` and `geo_region` governed tags exist, tagging the columns, creating the
# MAGIC row filter and column mask UDFs, and creating the ABAC policies themselves are all
# MAGIC expressible in SQL (via `CREATE POLICY`, GA on DBR 16.4+ or serverless) and run directly
# MAGIC in the cells below, no account console step required for any of it.

# COMMAND ----------

# MAGIC %md
# MAGIC ## Tag the sensitive columns
# MAGIC
# MAGIC Apply the `pii` tag to the `ssn` and `address` columns, and the `geo_region` tag to the
# MAGIC `region` column. This is ordinary `ALTER TABLE ... ALTER COLUMN ... SET TAGS` syntax,
# MAGIC whether or not the tag key has been governed in the account console.

# COMMAND ----------

# MAGIC %sql
# MAGIC ALTER TABLE testing.default.clients
# MAGIC ALTER COLUMN ssn
# MAGIC SET TAGS ('pii' = 'ssn');
# MAGIC
# MAGIC ALTER TABLE testing.default.clients
# MAGIC ALTER COLUMN address
# MAGIC SET TAGS ('pii' = 'address');
# MAGIC
# MAGIC ALTER TABLE testing.default.clients
# MAGIC ALTER COLUMN region
# MAGIC SET TAGS ('geo_region' = 'region');

# COMMAND ----------

# MAGIC %md
# MAGIC ## Row filter: hide EU customer rows
# MAGIC
# MAGIC First, a UDF that returns `TRUE` for a non-EU region and `FALSE` for `EU`. Filtering on a
# MAGIC dedicated, tagged region column like this is more reliable than a substring match against
# MAGIC a free-text address field.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE OR REPLACE FUNCTION testing.default.non_eu_region(region STRING)
# MAGIC RETURNS BOOLEAN
# MAGIC RETURN region <> 'EU';

# COMMAND ----------

# MAGIC %md
# MAGIC This function returns `FALSE` for EU-tagged rows, so the row filter policy hides them.
# MAGIC
# MAGIC In **Catalog Explorer**, the equivalent policy is created like this (shown for reference;
# MAGIC this UI path cannot be scripted from a notebook):
# MAGIC
# MAGIC - Navigate to **testing -> Policies -> New policy**
# MAGIC - Name: **hide_eu_customers**
# MAGIC - Applied to: **All account users**
# MAGIC - Scope: **Catalog = testing, schema = default, All tables**
# MAGIC - Purpose: **Hide table rows**
# MAGIC - Conditions: Use existing function -> select `non_eu_region`
# MAGIC - Function parameters: Map tag `geo_region:region` to the function parameter
# MAGIC - Save the policy
# MAGIC
# MAGIC At GA you can also create the same policy directly in SQL, which is what the cell below
# MAGIC runs:

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE POLICY hide_eu_customers
# MAGIC ON SCHEMA testing.default
# MAGIC COMMENT 'Hide EU customer rows from US analysts'
# MAGIC ROW FILTER testing.default.non_eu_region
# MAGIC TO `account users`
# MAGIC FOR TABLES
# MAGIC MATCH COLUMNS has_tag('geo_region') AS region
# MAGIC USING COLUMNS (region);

# COMMAND ----------

# MAGIC %md
# MAGIC Now every table in `testing.default` with a column tagged `geo_region` will have its
# MAGIC EU rows filtered for anyone matched by the policy's `TO` clause.

# COMMAND ----------

# MAGIC %sql
# MAGIC SELECT * FROM testing.default.clients;
# MAGIC -- Returns only non-EU customer rows

# COMMAND ----------

# MAGIC %md
# MAGIC ## Column mask: redact SSNs
# MAGIC
# MAGIC Next, a UDF that always returns a fixed, masked string in place of the real SSN value.

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE OR REPLACE FUNCTION testing.default.mask_ssn(ssn STRING)
# MAGIC RETURNS STRING
# MAGIC RETURN '***-**-****';

# COMMAND ----------

# MAGIC %md
# MAGIC In **Catalog Explorer**, the equivalent policy is created like this (shown for reference;
# MAGIC this UI path cannot be scripted from a notebook):
# MAGIC
# MAGIC - Go to **Policies -> New policy**
# MAGIC - Name: **mask_ssn**
# MAGIC - Applied to: **All account users**
# MAGIC - Scope: **Catalog = testing, schema = default, All tables**
# MAGIC - Purpose: **Mask column data**
# MAGIC - Condition: Mask column if tagged with `pii:ssn`
# MAGIC - Function: Select existing = `mask_ssn`
# MAGIC - Save the policy
# MAGIC
# MAGIC At GA you can also create the same policy directly in SQL, which is what the cell below
# MAGIC runs:

# COMMAND ----------

# MAGIC %sql
# MAGIC CREATE POLICY mask_ssn
# MAGIC ON SCHEMA testing.default
# MAGIC COLUMN MASK testing.default.mask_ssn
# MAGIC TO `account users`
# MAGIC FOR TABLES
# MAGIC MATCH COLUMNS has_tag_value('pii', 'ssn') AS ssn
# MAGIC ON COLUMN ssn;

# COMMAND ----------

# MAGIC %md
# MAGIC ## Verify
# MAGIC
# MAGIC With both policies in place, querying the table now returns only non-EU rows, and the
# MAGIC `ssn` column is replaced with the masked value for anyone matched by the policies' `TO`
# MAGIC clause. If you run this notebook as a catalog owner or metastore admin, enforcement may
# MAGIC look different than for an ordinary account user; test with a non-privileged user or
# MAGIC group if you need to confirm end-user behavior exactly.

# COMMAND ----------

# MAGIC %sql
# MAGIC SELECT * FROM testing.default.clients;
# MAGIC -- Non-EU rows only, with SSNs replaced by ***-**-****

# COMMAND ----------

# MAGIC %md
# MAGIC The same check from PySpark, counting what remains visible after both policies apply:

# COMMAND ----------

visible = spark.table(table)
display(
    visible
    .select(F.col("id"), F.col("region"), F.col("ssn"))
    .orderBy(F.col("id"))
)
print(f"Visible rows after the row filter: {visible.count()}")

