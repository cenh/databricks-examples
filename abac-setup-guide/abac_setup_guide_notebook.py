# MAGIC %md
# MAGIC ## Setup
# MAGIC
# MAGIC Create the CH Enterprise `clients` table in the `testing.default` catalog and
# MAGIC schema: eight sample client records, four in the US and four in the EU, each with an
# MAGIC address, a Social Security Number (SSN), and a region. `id` is declared as an identity
# MAGIC column so it does not need to be supplied when writing rows.

# COMMAND ----------

catalog = "testing"
schema = "default"
table = f"{catalog}.{schema}.clients"

spark.sql(f"CREATE CATALOG IF NOT EXISTS {catalog}")
spark.sql(f"CREATE SCHEMA IF NOT EXISTS {catalog}.{schema}")

spark.sql(f"""
CREATE TABLE IF NOT EXISTS {table} (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  address STRING,
  ssn STRING,
  region STRING
)
USING DELTA
""")

data = [
    ("123 Main St, NY, US", "123-45-6789", "US"),
    ("456 Oak St, CA, US", "234-56-7890", "US"),
    ("12 Abbey Street, Dublin, Ireland", "111-22-3333", "EU"),
    ("45 Rue de Rivoli, Paris, France", "222-33-4444", "EU"),
    ("789 Pine St, TX, US", "345-67-8901", "US"),
    ("23 Via Roma, Milan, Italy", "444-55-6666", "EU"),
    ("321 Maple St, FL, US", "456-78-9012", "US"),
    ("78 Berliner Str., Berlin, Germany", "333-44-5555", "EU"),
]

df = spark.createDataFrame(data, ["address", "ssn", "region"])
df.write.mode("append").saveAsTable(table)

display(spark.table(table))

# COMMAND ----------

# MAGIC %md
# MAGIC Before any ABAC policy exists, every column and every row is fully visible to any reader
# MAGIC with `SELECT` on the table. Confirm the US/EU split now, so the row filter's effect later
# MAGIC is easy to check.

# COMMAND ----------

import pyspark.sql.functions as F

region_counts = (
    spark.table(table)
    .groupBy(F.col("region"))
    .agg(F.count("*").alias("num_clients"))
    .orderBy(F.col("region"))
)
display(region_counts)

